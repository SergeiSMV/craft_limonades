package model

import (
	"errors"
)

// Дефолты физического склада и его ячейки приёмки.
//
// Зачем константы, а не значения по месту: их спрашивают трое - импорт ячеек (склад из файла
// не приходит), сидер (в пустой базе склада нет вовсе) и приёмка (ячейка по умолчанию). Разъедься
// они хоть на символ - сидер завёл бы один склад, импорт второй, и приёмка искала бы ячейку не там.
//
// ⚠ Пилот идёт на одном складе; переопределяются переменными окружения WAREHOUSE_CODE /
// WAREHOUSE_NAME (сидер) и полями формы warehouse_code / warehouse_name (импорт).
const (
	// DefaultWarehouseCode - короткий код физического склада пилота («Шабулина»), согласован с заказчиком.
	DefaultWarehouseCode = "SHB"
	// DefaultWarehouseName - как склад показывается человеку.
	DefaultWarehouseName = "Шабулина"
	// DefaultCellAddress - адрес ячейки приёмки по умолчанию.
	//
	// Это ИМЯ ячейки, а не адрес на стеллаже. До ADHOC-61 ячейкой приёмки была «С-Н-П», но это
	// пол у стеллажа C - напольное хранение (FloorStorageSuffix). Код ищет ячейку приёмки по
	// флагу cells.is_default, а не по этой строке, - переименование не должно ломать приёмку.
	// Константа нужна только тем, кто ячейку СОЗДАЁТ.
	DefaultCellAddress = "ПРИЁМКА"
	// ShippingCellAddress - адрес ячейки отгрузки (P9-02): короба собранных заказов до отгрузки.
	ShippingCellAddress = "ОТГРУЗКА"

	// FloorStorageSuffix - окончание адреса напольной ячейки: «пол» у стеллажа, «D-Н-П» (ADHOC-61).
	// Так пол адресует 1С в реестре на сборку.
	FloorStorageSuffix = "-Н-П"
)

// ErrInvalidInternalWarehouse - код или имя склада не годятся: код - латиница в верхнем
// регистре, цифры и «_» до 20 знаков, имя - непустое, до 100 символов.
var ErrInvalidInternalWarehouse = errors.New("invalid internal warehouse code or name")
