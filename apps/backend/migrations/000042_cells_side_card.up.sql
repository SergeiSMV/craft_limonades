-- ADHOC-57: признак «на карточке» переезжает со стеллажа на ячейку.
--
-- Что: у ячейки - признак side_card «строка на карточке своего стеллажа»; у стеллажа признак
-- карточки убирается, стеллаж остаётся только группировкой (код «B-01»).
-- Зачем: решение 2026-11-05 - какие ячейки попадают на карточку на стойку, решает человек
-- галочкой у ячейки, а не правило «весь стеллаж без штрих-кода на балке». Карточка печатается
-- на стеллаж, где есть хоть одна ячейка с галочкой.
-- Как: галочку получают ячейки, которые печатались на карточке по прежнему правилу - стеллаж
-- с карточкой и ячейка без штрих-кода на балке; напечатанное до миграции не меняется. У ячейки
-- без стеллажа карточки нет - признак держит сервис (галочку ставит только ячейке со стеллажом).

ALTER TABLE cells
    ADD COLUMN side_card boolean NOT NULL DEFAULT false;  -- строка на карточке стеллажа

UPDATE cells c SET side_card = true
FROM racks r
WHERE r.id = c.rack_id AND r.side_card AND NOT c.label_barcode;

ALTER TABLE racks DROP COLUMN side_card;
