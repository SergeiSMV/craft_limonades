-- P3-01: документы отчётов — неизменяемый снимок содержимого на момент завершения операции.
--
-- Зачем. Отчёт собирался запросом по ЖИВЫМ справочникам (goods, cells, warehouses), а импорт
-- номенклатуры — апсерт по «Код». Значит переименование товара в 1С меняло уже выданный документ:
-- оператор заносит файл в 1С, через неделю скачивает тот же документ для сверки и видит другие
-- наименования, а вместе с ними и другой порядок строк (сортировка шла по имени товара).
-- Документ, служащий основанием проводки, так вести себя не должен.
--
-- Почему снимок в БД, а не файл на диске. Файлы потребовали бы второго канала бэкапа: pg-backup.sh
-- увозит во внешнюю копию только pg_dump, и восстановление дало бы записи о документах без самих
-- документов. Снимок попадает в существующий шифрованный бэкап бесплатно. Генерация XLSX при этом
-- дёшева (тысяча строк — миллисекунды), поэтому файл собирается из снимка на каждое скачивание,
-- и правка шаблона задним числом применяется ко всем документам, не трогая их данные.
--
-- Как. Снимок пишется В ТОЙ ЖЕ транзакции, что и закрытие операции: документ и факт завершения
-- живут или умирают вместе. Тот же приём, что у processed_operations (000008).
CREATE TABLE report_documents (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    kind        text        NOT NULL,                     -- форма отчёта: какой шаблон применять
    source_type text        NOT NULL,                     -- вид операции-источника
    source_id   uuid        NOT NULL,                     -- сама операция
    snapshot    jsonb       NOT NULL,                     -- замороженное содержимое: шапка + строки
    created_at  timestamptz NOT NULL DEFAULT now(),

    -- Один документ на операцию: повторный финал (в т.ч. повтор из очереди устройства)
    -- не плодит копий. Пара, а не source_id один: идентификаторы разных таблиц-источников
    -- независимы и теоретически могут совпасть.
    UNIQUE (source_type, source_id)
);

-- kind и source_type намеренно РАЗНЫЕ поля, хотя сегодня у единственного типа документа они
-- дублируют друг друга. Связь не один-к-одному: «Движение» (одна форма) рождается размещением,
-- перемещением и пополнением (три источника, P5-P6), а один источник может дать разные формы.
--
-- CHECK со списком значений не ставим: список пополняется в каждой следующей фазе (P4 — приёмка,
-- P5/P6 — движение), и ограничение означало бы миграцию на каждый новый отчёт. Выигрыша нет:
-- значение приходит из кода сервиса, а не от пользователя.

-- Список документов в портале: свежие сверху, в пределах своей формы.
CREATE INDEX report_documents_kind_created_at_idx ON report_documents (kind, created_at DESC);

COMMENT ON TABLE report_documents IS
    'P3-01: документы отчётов; snapshot — содержимое, замороженное на момент завершения операции';
COMMENT ON COLUMN report_documents.snapshot IS
    'Содержимое документа целиком. Читается вместо запроса к справочникам, поэтому переименование '
    'товара или правка адреса ячейки не меняют уже выданный документ.';

-- Бэкофилл: закрытые до этой миграции сессии ввода остатков получают снимок из текущих данных.
-- Без него список документов в портале показывал бы записи, которые невозможно скачать.
-- Точность бэкофилла ограничена: справочники с момента закрытия могли измениться, и снимок
-- фиксирует их СЕГОДНЯШНЕЕ состояние — лучшее из доступного, дальше расхождение не растёт.
INSERT INTO report_documents (kind, source_type, source_id, snapshot, created_at)
SELECT
    'stock_entry',
    'stock_entry_session',
    s.id,
    jsonb_build_object(
        'warehouse_code', w.code,
        'warehouse_name', w.name,
        -- RFC3339 в UTC: Go разбирает его time.RFC3339 без догадок о локали сервера.
        'created_at', to_char(s.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
        'rows', COALESCE((
            SELECT jsonb_agg(jsonb_build_object(
                       'cell_address',    c.address,
                       'good_code',       g.code,
                       'good_name',       g.name,
                       'production_date', l.production_date::text,
                       'qty',             l.qty::text
                   ) ORDER BY c.address, g.name)
            FROM stock_entry_lines l
            JOIN cells c ON c.id = l.cell_id
            JOIN goods g ON g.id = l.good_id
            WHERE l.session_id = s.id
        ), '[]'::jsonb)
    ),
    COALESCE(s.closed_at, s.created_at)
FROM stock_entry_sessions s
JOIN warehouses w ON w.id = s.warehouse_id
WHERE s.status = 'closed'
ON CONFLICT (source_type, source_id) DO NOTHING;
