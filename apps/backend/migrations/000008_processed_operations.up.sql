-- P2-05: журнал применённых операций — ключ идемпотентности офлайн-очереди устройства.
--
-- Зачем. Операция на ТСД рождается ДО сетевого вызова (Outbox, P2-03) и повторяется, пока не
-- подтверждена (P2-04). Повтор неизбежен и штатен: попытка могла оборваться уже после того, как
-- сервер её применил, — процесс на устройстве умер, ответ не дошёл, статус `sending` остался.
--
-- ⚠ Часть операций переживает повтор и без журнала — и это не случайность, а прежние решения:
-- привязка ШК вставляется через ON CONFLICT DO NOTHING (P-FS-03), строка сессии пишется
-- SET-семантикой через ON CONFLICT DO UPDATE (P-FS-02/P-FS-04). Журнал нужен там, где такой
-- защиты нет:
--   * ФИНАЛ сессии. Повтор упирается в проверку статуса и возвращает 409 «уже закрыта» — то есть
--     успешная операция приезжает на устройство ОТКАЗОМ и оседает на экране разбора как ошибка,
--     хотя остатки записаны. Журнал отдаёт повтору исходный ответ, а не отказ.
--   * Будущие операции с семантикой ПРИРАЩЕНИЯ — приёмка (P4) и перемещение (P6) поверх
--     addStock/removeStock. Там повтор буквально удваивает движение, и защиты «на месте» нет.
-- Уповать на то, что каждый новый эффект окажется идемпотентным сам по себе, нельзя: это
-- свойство надо каждый раз доказывать заново, а журнал даёт его один раз для всех.
--
-- Как. Клиент присылает `operation_id` (UUID v4, сгенерирован на устройстве), сервер помечает его
-- здесь В ТОЙ ЖЕ транзакции, что и сам эффект. Отметка и эффект живут или умирают вместе: падение
-- между ними невозможно, потому что между ними нет границы транзакции.
CREATE TABLE processed_operations (
    operation_id uuid        PRIMARY KEY,                        -- ключ идемпотентности с устройства
    kind         text        NOT NULL,                           -- тип операции (для разбора и метрик)
    result       jsonb       NOT NULL DEFAULT '{}'::jsonb,       -- ответ, отданный в первый раз
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- Разбор «что приезжало за последние сутки» и будущая чистка журнала по возрасту.
CREATE INDEX processed_operations_created_at_idx ON processed_operations (created_at);

COMMENT ON TABLE processed_operations IS
    'P2-05: применённые операции очереди устройства; повтор по operation_id отбрасывается';
COMMENT ON COLUMN processed_operations.result IS
    'Ответ первой попытки. Повтор получает ЕГО ЖЕ, а не пустой успех: клиенту нужен тот же '
    'session_id/число строк, что и в первый раз, иначе ответ на повтор противоречил бы первому.';
