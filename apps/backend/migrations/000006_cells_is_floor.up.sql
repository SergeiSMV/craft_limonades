-- P1-05: импорт физических ячеек склада из файла (.xlsx).
--
-- Ячейка ФИЗИЧЕСКАЯ и принадлежит физическому (внешнему) складу «Шабулина» = строке warehouses.
-- «Внутренний склад» (основной/брак/…) - это НЕ свойство ячейки, а измерение ОСТАТКА (stock):
-- одна физическая ячейка держит остатки разных внутренних складов одновременно (ADR-0016).
-- Поэтому здесь на уровне ячейки добавляем только признак напольной - из колонки файла `floor`.
--
-- is_floor - напольная ячейка (нижний ярус): на будущей генерации PDF со штрихкодами такие
-- ячейки помечаются стрелкой вниз. Дефолт false - существующие/ручные ячейки не напольные.
ALTER TABLE cells ADD COLUMN is_floor boolean NOT NULL DEFAULT false;
