-- P3-02: статус документа - «новый» → «скачан» → «выполнен».
--
-- Зачем. Оператор скачивает документ, заносит его в 1С и отмечает выполненным. Без статуса
-- список документов - это просто перечень: непонятно, что уже унесено в 1С, а что ждёт.
-- Именно ради трекаемого рабочего списка e-mail-доставку и заменили порталом (ADR-0013):
-- письмо уходило и забывалось, а необработанный документ должен оставаться на виду.
--
-- Переходы. new → downloaded ставит сама выдача файла; done - кнопка «Выполнено» в портале.
-- Скачать можно и повторно, в том числе выполненный: сам факт скачивания статус НЕ откатывает,
-- иначе документ, уже занесённый в 1С, вернулся бы в работу от одного просмотра.
-- Отметить выполненным можно и минуя скачивание: данные могли попасть в 1С другим путём,
-- и запрещать это значило бы навязывать порядок действий, которого нет в жизни.
ALTER TABLE report_documents
    ADD COLUMN status        text        NOT NULL DEFAULT 'new'
                             CHECK (status IN ('new','downloaded','done')),
    ADD COLUMN downloaded_at timestamptz,   -- первое скачивание; NULL - ещё не скачивали
    ADD COLUMN done_at       timestamptz;   -- отметка «занесено в 1С»

-- Список в портале: сначала необработанные, свежие сверху. Индекс покрывает и фильтр по статусу,
-- и сортировку внутри него.
CREATE INDEX report_documents_status_created_at_idx ON report_documents (status, created_at DESC);

COMMENT ON COLUMN report_documents.status IS
    'P3-02: new (опубликован) → downloaded (скачан) → done (занесён в 1С). Повторное скачивание '
    'статус не откатывает; отметка «выполнен» возможна и без скачивания.';
COMMENT ON COLUMN report_documents.downloaded_at IS 'Момент ПЕРВОГО скачивания; повтор его не двигает.';
