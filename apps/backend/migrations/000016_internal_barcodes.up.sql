-- P4-07: внутренние штрихкоды для товаров, у которых своего ШК нет.
--
-- Зачем. Часть номенклатуры приезжает из 1С без штрихкода - на упаковке его просто нет.
-- Такой товар нельзя отсканировать, то есть он выпадает из всей работы склада: его не принять
-- сканом, не найти в ячейке, не собрать в заказ. Решение - напечатать свой ШК и наклеить.
--
-- Почему EAN-13 с префиксом 20-29 (решение заказчика, вопрос №4): диапазон зарезервирован GS1
-- под внутреннее использование, то есть производитель такой код выдать не может, и столкновение
-- с кодом из выгрузки 1С исключено по построению. Контрольная цифра живёт В САМИХ ДАННЫХ -
-- она ловит опечатку ручного ввода, а не только ошибку скана.

-- Признак «этот ШК выдали мы».
--
-- Флаг, а не разбор префикса строки. Префикс 20-29 действительно наш по договорённости,
-- но выгрузка 1С может принести чужой внутренний код прежней системы, начинающийся так же,
-- и тогда поиск по префиксу выдал бы чужой ШК за свой. Тот же приём, что у cells.is_default
-- и internal_warehouses.is_default: признак принадлежности хранится, а не вычисляется.
ALTER TABLE barcodes ADD COLUMN is_internal boolean NOT NULL DEFAULT false;

-- «Какой внутренний ШК у этого товара» - запрос, который делается перед каждой генерацией,
-- чтобы не выдать товару второй код. Частичный индекс: внешних ШК на порядки больше,
-- и держать их в этом индексе незачем.
CREATE INDEX barcodes_internal_good_idx ON barcodes (good_id) WHERE is_internal;

COMMENT ON COLUMN barcodes.is_internal IS
    'P4-07: ШК выдан нами (внутренний EAN-13 с префиксом 20-29), а не пришёл из выгрузки.';

-- Источник серийных номеров внутренних ШК.
--
-- Последовательность, а не выбор max()+1: при двух одновременных генерациях второй вариант
-- выдал бы один номер дважды, и вторая вставка упала бы на UNIQUE(barcode). Последовательность
-- отдаёт номера без блокировок и переживает перезапуск.
--
-- Дыры в нумерации допустимы: откатившаяся транзакция свой номер не возвращает. Номер - не
-- документ и не отчётная единица, поэтому непрерывность здесь ничего не стоит.
--
-- Потолок 10^10 − 1 - это десять цифр, ровно столько остаётся в EAN-13 после двузначного
-- префикса и контрольной цифры. На складских объёмах недостижим.
CREATE SEQUENCE internal_barcode_serial AS bigint START 1 MINVALUE 1 MAXVALUE 9999999999;

COMMENT ON SEQUENCE internal_barcode_serial IS
    'P4-07: серийные номера внутренних ШК; 10 цифр - всё, что остаётся в EAN-13 после префикса и контрольной цифры.';
