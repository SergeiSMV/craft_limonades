-- P4-03: дефолтная ячейка склада — та, куда приходуют, если ячейку не указали.
--
-- Зачем. Приёмка не заставляет кладовщика выбирать место: короб уезжает в ячейку «С-Н-П»,
-- если он не сказал иного (решение заказчика). Домен приёмки (P4-02) ячейку требует явно —
-- подставляет умолчание слой выше, и вот откуда он его берёт.
--
-- Почему флаг, а не строка адреса в коде. `С-Н-П` — это ИМЯ ячейки, а не шаблон
-- «стеллаж-секция-полка», как читался комментарий к `cells.address`. Имя переименуют — код
-- искать её по строке перестал бы молча. Флаг переживает переименование; приём тот же, что
-- у `internal_warehouses.is_default` (ADR-0016), и код там уже не знает про код 'MAIN'.
ALTER TABLE cells ADD COLUMN is_default boolean NOT NULL DEFAULT false;

-- Ровно одна дефолтная ячейка НА СКЛАД — частичный уникальный индекс по warehouse_id.
-- Здесь, в отличие от внутренних складов, индекс не по константе: складов может быть несколько,
-- и у каждого своя ячейка по умолчанию.
CREATE UNIQUE INDEX cells_default_idx ON cells (warehouse_id) WHERE is_default;

COMMENT ON COLUMN cells.is_default IS
    'P4-03: ячейка приёмки по умолчанию (С-Н-П). Одна на склад — частичный уникальный индекс.';

-- Бэкофилл: у каждого уже заведённого склада появляется своя `С-Н-П`.
--
-- Без этого приёмка на существующем складе упиралась бы в «нет дефолтной ячейки»: склады
-- заводятся импортом ячеек, и на проде они уже есть, а флага у их ячеек нет ни у одной.
-- Если такая ячейка в складе уже импортирована из файла — она же и становится дефолтной,
-- второй строки не появляется (грань (warehouse_id, address) из P1-01).
INSERT INTO cells (warehouse_id, address, is_default)
SELECT id, 'С-Н-П', true FROM warehouses
ON CONFLICT (warehouse_id, address) DO UPDATE SET is_default = true;
