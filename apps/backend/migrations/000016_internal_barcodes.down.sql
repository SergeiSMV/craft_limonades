-- P4-07: откат внутренних штрихкодов.
--
-- ⚠ Сами ШК НЕ удаляются: они напечатаны и наклеены на товар. Снимается только признак
-- принадлежности, по которому их отличали от пришедших из выгрузки. Наклейка на коробке
-- переживёт любой откат схемы, и удаление привязки сделало бы отсканированный товар
-- неопознаваемым — цена несоразмерная откату одной колонки.
DROP INDEX IF EXISTS barcodes_internal_good_idx;
ALTER TABLE barcodes DROP COLUMN IF EXISTS is_internal;
DROP SEQUENCE IF EXISTS internal_barcode_serial;
