-- P4-03: откат признака дефолтной ячейки.
--
-- Снимается только ПРИЗНАК. Сами ячейки `С-Н-П` остаются: к моменту отката в них уже мог
-- лечь остаток, и удаление унесло бы товар вместе с ними - ради отката признака это цена
-- несоразмерная. Лишняя пустая ячейка безвредна, потерянный остаток - нет.
DROP INDEX IF EXISTS cells_default_idx;
ALTER TABLE cells DROP COLUMN IF EXISTS is_default;
