/// Что движок знает о связи с сервером (P2-07).
///
/// **Почему не «есть Wi-Fi / нет Wi-Fi».** Связность и доступность сервера на складе расходятся
/// регулярно: стеллажи, металл, точка доступа в другом конце здания. Индикатор, построенный на
/// одном событии сети, показывал бы «онлайн» ровно там, где кладовщик не может отправить работу,
/// — то есть врал бы в единственный момент, когда он нужен. Это уже зафиксировано решением
/// P2-04: источник истины о доступности сервера — сама попытка обмена.
///
/// Отсюда асимметрия, на которой держится весь тип: **«сети нет» — надёжный негатив** (без сети
/// сервер недостижим наверняка), **«сеть есть» — не доказательство**. Поэтому `online` ставится
/// только по факту удавшегося обмена, а `offline` — и по событию сети, и по неудаче обмена.
enum LinkState {
  /// Обменов ещё не было — утверждать нечего.
  ///
  /// Отдельное значение, а не «офлайн по умолчанию»: показать «нет связи» там, где мы просто
  /// не пробовали, значит соврать в другую сторону и научить не доверять индикатору.
  unknown,

  /// Последний обмен с сервером удался.
  online,

  /// Сети нет вовсе либо последняя попытка обмена не удалась.
  offline,
}
