/// Черновик незавершённой работы кладовщика - контракт для экранов (ADHOC-71).
///
/// Что: прочитать, сохранить, стереть слепок и следить, есть ли он.
/// Зачем отдельно от [DraftSlot]: слот - хранение в drift (слой данных), а cubit и главный
/// экран должны знать только «есть черновик / сохранить / стереть» (`dev.md §2`). Каждая фича
/// заводит в своём `domain` пустой наследник (`ReceiptDrafts`, `PutawayDrafts`) - по нему
/// контейнер зависимостей отличает черновик одного потока от другого.
abstract interface class Drafts {
  /// Прочитать слепок; `null` - незавершённой работы нет.
  Future<Map<String, dynamic>?> load();

  /// Сохранить слепок (перезаписывает предыдущий).
  Future<void> save(Map<String, dynamic> draft);

  /// Есть ли незавершённая работа - живой признак для пометки на входе в раздел (ADHOC-13).
  Stream<bool> watchHasDraft();

  /// Стереть слепок - работа завершена или отброшена.
  Future<void> clear();
}
