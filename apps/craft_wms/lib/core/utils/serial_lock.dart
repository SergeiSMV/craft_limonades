import 'dart:async';

/// Последовательное выполнение асинхронных действий (ADHOC-63).
///
/// Что: [run] ставит действие в цепочку - следующее начинается, только когда закончилось
/// предыдущее, в порядке вызова.
/// Зачем: сканы идут быстрее, чем отвечает база и сервер. Без очереди два скана подряд
/// обрабатывались одновременно и видели состояние без пика друг друга, а чтение-изменение-
/// запись одного слепка затирало свой же пик.
/// Как: хвост цепочки - `Future` последнего действия; ошибка действия возвращается его
/// вызывающему и цепочку не рвёт.
class SerialLock {
  Future<void> _tail = Future.value();

  /// Выполнить [action] после всех ранее поставленных.
  Future<T> run<T>(Future<T> Function() action) {
    final result = _tail.then((_) => action());
    _tail = result.then<void>((_) {}, onError: (Object _) {});
    return result;
  }
}
