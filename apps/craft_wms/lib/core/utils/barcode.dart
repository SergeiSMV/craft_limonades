/// Похоже ли введённое на штрихкод товара: только цифры и не короче 8 знаков
/// (EAN-8 / EAN-13 и числовые Code128 из выгрузки 1С).
///
/// Зачем: в строку поиска «Остатков» попадает и скан с ТСД, и набранное руками наименование.
/// По Enter скан нужно резолвить как ШК, а обычный текст — искать подстрокой; отличаем их
/// по форме ввода, иначе поиск по названию каждый раз упирался бы в «ШК не найден».
bool looksLikeBarcode(String input) => RegExp(r'^\d{8,}$').hasMatch(input.trim());
