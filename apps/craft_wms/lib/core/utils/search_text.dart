/// Нормализация текста под поиск товаров.
///
/// Что: приводит строку к виду, по которому идёт сравнение — нижний регистр и «ё» → «е».
/// Зачем: поиск должен находить «Фома Лукич» по запросу «фома лукич» и «бекон» по «бёкон»,
///        а хранить оба варианта в базе незачем.
/// Как: одна и та же функция применяется и к содержимому справочника при укладке в кэш,
///      и к пользовательскому запросу — иначе нормализация разъедется между ними.
///
/// Повторяет правила серверного поиска из P-FS-17 (`searchWords` в `service/catalog.go`),
/// чтобы локальный и серверный поиск давали одинаковый результат.
String normalizeSearchText(String value) => value.toLowerCase().replaceAll('ё', 'е');

/// Разбор поискового запроса на слова.
///
/// Правило поиска — «все слова присутствуют, порядок не важен»: «фома бекон» находит
/// «Арахис в хрустящей корочке Бекон (ТМ Фома Лукич)». Пустые слова отбрасываются,
/// число слов ограничено [maxWords]: запрос из сотни слов превратился бы в сотню условий.
List<String> searchWords(String query, {int maxWords = 10}) {
  final words = normalizeSearchText(query)
      .split(RegExp(r'\s+'))
      .where((word) => word.isNotEmpty)
      .toList();
  return words.length > maxWords ? words.sublist(0, maxWords) : words;
}
