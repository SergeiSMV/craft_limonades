import 'failure.dart';

/// Причина отказа в виде, пригодном для показа человеку и для хранения в очереди операций.
///
/// Что: короткая строка вместо `toString()` доменного объекта.
/// Зачем: в отклонённой операции причина - единственное, по чему кладовщик поймёт, что делать
///        дальше: повторить или отбросить. Строка `Failure.server(409, null)` не говорит ему
///        ничего, а именно она и лежала в очереди до P2-06.
/// Как: если сервер прислал объяснение - берём его дословно, он знает больше нас. Иначе
///      остаётся код: он хотя бы отличает «занято» от «сломалось».
///
/// Текст здесь намеренно не переводится через slang: он **хранится в базе**, а не рисуется.
/// Локализованная строка в базе протухнет при первой же правке формулировки, поэтому экран
/// показывает её как есть - как цитату ответа сервера.
String failureReason(Failure failure) => switch (failure) {
  NetworkFailure() => 'нет связи',
  AuthFailure() => 'сессия истекла',
  ServerFailure(:final statusCode, :final message) =>
    message?.isNotEmpty ?? false ? message! : 'сервер отказал ($statusCode)',
  // Причина уже пришла от сервера дословно - она и есть текст.
  RejectedFailure(:final reason) => reason,
  UnknownFailure(:final message) =>
    message?.isNotEmpty ?? false ? message! : 'неизвестная ошибка',
};
