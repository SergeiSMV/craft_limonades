/// Коробочный ярлык грузовой единицы (P4-06).
///
/// Что: QR с идентификатором короба и короткий код для глаз.
/// Зачем короткий код рядом с QR: ярлык на коробе живёт в условиях склада — его трут, мнут
/// и заливают. Нечитаемый QR без человекочитаемого дубля означал бы короб, который система
/// знает, а человек найти не может.
/// Как: родным текстом принтера, а не графикой. Проверено на живом XP-P323B — встроенные
/// шрифты берут кириллицу при `CODEPAGE 1251`, поэтому картинка не нужна: команды весят
/// сотни байт против ~18 КБ растра, печатаются мгновенно и не зависят от загруженных шрифтов.
///
/// Состав ярлыка намеренно минимален (решение заказчика): всё остальное — поставщик, дата,
/// документ приёмки — живёт в системе и видно по скану. Чем меньше на ярлыке, тем меньше на нём
/// того, что может устареть: короб переложат, а напечатанное останется.
class LoadUnitLabel {
  const LoadUnitLabel(this.loadUnitId);

  /// Идентификатор ГЕ (UUID). В QR уезжает он же, обёрнутый в формат ярлыка (P4-04).
  final String loadUnitId;

  /// Отступ от края этикетки в точках. 2 мм при 203 dpi — меньше брать нельзя:
  /// подача гуляет, и напечатанное у самого края срезается.
  static const int _margin = 16;

  /// Ширина модуля QR в точках. 8 даёт код около 29 мм — он читается сканером ТСД
  /// с потёртого короба, а не только со свежей наклейки.
  static const int _qrCell = 8;

  /// Короткий код для глаз: последние 8 шестнадцатеричных знаков идентификатора, заглавными
  /// и разбитые пополам.
  ///
  /// Почему хвост, а не начало: у UUID v4 случайна вся вторая половина, а первые группы у
  /// соседних кодов могут совпасть по удачному стечению. Разбивка на две четвёрки — чтобы
  /// человек не терял место, перенося код глазами.
  ///
  /// ⚠ Это код ДЛЯ ЧЕЛОВЕКА, а не идентификатор: 8 знаков не гарантируют уникальность,
  /// и система по-прежнему опознаёт короб по QR целиком.
  String get shortCode {
    final hex = loadUnitId.replaceAll('-', '').toUpperCase();
    final tail = hex.length >= 8 ? hex.substring(hex.length - 8) : hex;
    return tail;
  }

  /// Короткий код в читаемом виде: две четвёрки через пробел.
  ///
  /// Разбивка — чтобы человек не терял место, перенося код глазами: восемь знаков подряд
  /// читаются заметно хуже, особенно на мятой наклейке.
  String get shortCodeFormatted {
    final code = shortCode;
    if (code.length < 4) return code;
    final half = code.length ~/ 2;
    return '${code.substring(0, half)} ${code.substring(half)}';
  }

  /// Приводит код, набранный человеком, к виду для сравнения: без пробелов, заглавными.
  ///
  /// Зачем здесь, рядом с печатью: на ярлыке код разбит пробелом, и человек набирает его
  /// так, как видит. Поиск, не терпящий пробела, превратил бы читаемую разбивку в ловушку.
  ///
  /// ⚠ Наклейки переживают наши решения: ярлыки, напечатанные с пробелом, будут ездить
  /// на коробах и после любой смены формата. Поэтому терпимость к пробелу — не удобство,
  /// а требование совместимости. Поиск по короткому коду (`P4-09`) обязан звать эту функцию.
  static String normalizeShortCode(String input) =>
      input.replaceAll(RegExp(r'[\s-]'), '').toUpperCase();

  /// Команды TSPL для печати ярлыка.
  ///
  /// Раскладка: QR по центру сверху, короткий код под ним мелким шрифтом. QR занимает всю
  /// ширину, какую может, — он рабочий элемент ярлыка, а код лишь подстраховка на случай,
  /// когда QR затёрт.
  List<int> tspl(LabelGeometry geometry) {
    final payload = encodeLoadUnitPayload(loadUnitId);
    final qrSide = qrModules(payload.length) * _qrCell;
    final qrLeft = ((geometry.widthDots - qrSide) / 2).round().clamp(
      _margin,
      10000,
    );

    // Шрифт «3» — 16×24 точки, около 2×3 мм. Мельче брать нельзя: код читают с короба
    // на стеллаже, а не с ладони. Шрифт «5» (32×48) пробовали — он съедал пол-этикетки.
    const font = '3';
    const fontWidth = 16;
    const fontHeight = 24;
    final code = shortCodeFormatted;
    final codeLeft = ((geometry.widthDots - code.length * fontWidth) / 2)
        .round()
        .clamp(_margin, 10000);
    // Код прижат к низу: так он не зависит от того, насколько вырос QR.
    final codeTop = geometry.heightDots - _margin - fontHeight;

    return encodeCommands(
      'SIZE ${_mm(geometry.widthMm)} mm,${_mm(geometry.heightMm)} mm\r\n'
      'GAP ${_mm(geometry.gapMm)} mm,0 mm\r\n'
      'DIRECTION 1\r\n'
      'CLS\r\n'
      'CODEPAGE 1251\r\n'
      // ECC уровня M: держит до 15% повреждений. Выше брать незачем — код вырос бы
      // в модулях, а значит уменьшился бы физически при той же ширине этикетки.
      'QRCODE $qrLeft,$_margin,M,$_qrCell,A,0,"$payload"\r\n'
      'TEXT $codeLeft,$codeTop,"$font",0,1,1,"$code"\r\n'
      'PRINT 1,1\r\n',
    );
  }

  /// Сколько модулей в QR с полезной нагрузкой длиной [payloadLength] байт.
  ///
  /// Нужно только для раскладки — сам код строит принтер. Но без этой оценки QR нельзя
  /// поставить по центру: его ширина заранее неизвестна, а выравнивание «на глаз» поехало бы
  /// при любой смене формата ярлыка.
  ///
  /// Границы — ёмкость байтового режима с коррекцией M: версия 1 держит 14 байт (21 модуль),
  /// 2 — 26 (25), 3 — 42 (29), 4 — 62 (33). Наша нагрузка `CWLU1:` + UUID — ровно 42 байта,
  /// то есть версия 3; таблица нужна, чтобы смена формата не потребовала правки раскладки.
  static int qrModules(int payloadLength) => switch (payloadLength) {
    <= 14 => 21,
    <= 26 => 25,
    <= 42 => 29,
    <= 62 => 33,
    _ => 37,
  };
}

/// Размер в формате TSPL: целые без хвостового нуля.
String _mm(double value) => value == value.roundToDouble()
    ? '${value.round()}'
    : value.toStringAsFixed(1);

/// Кириллица в команды — на будущее: состав ярлыка сейчас без русского текста, но кодировщик
/// обязан быть под рукой там же, где строится ярлык (P4-08 печатает наименование товара).
List<int> labelText(String text) => encodeCp1251(text);
