import 'printer_device.dart';

/// Транспорт до принтера этикеток: соединение и поток байтов (P4-05).
///
/// Интерфейс, а не прямой вызов платформенного канала, по двум причинам. Первая — языки печати
/// (TSPL, ZPL) и способ доставки меняются независимо: это разные решения, и смешивать их в одном
/// классе значило бы переписывать печать при смене кабеля. Вторая — USB и Wi-Fi остаются точками
/// расширения: принтер понимает все три транспорта, и Bluetooth выбран как основной, а не
/// единственно возможный (решение по вопросу №6).
abstract interface class PrinterTransport {
  /// Состояние адаптера и соединения.
  Future<PrinterStatus> status();

  /// Устройства, уже спаренные с терминалом, — основной путь выбора принтера.
  Future<List<PrinterDevice>> bondedDevices();

  /// Поиск новых устройств. Поток завершается сам, когда обнаружение закончилось.
  /// Отписка гасит поиск: он занимает радио и сажает батарею.
  Stream<PrinterDevice> discover();

  /// Спарить терминал с принтером и дождаться исхода.
  ///
  /// Отдельным шагом, а не «само выйдет при подключении»: неявное спаривание Android ведёт
  /// по упрощённому пути, без запроса PIN, и на принтере это срывается аутентификацией.
  /// Уже спаренное устройство проходит шаг мгновенно.
  Future<void> bond(String address);

  /// Открыть соединение. Держится между этикетками — установка сокета заметно долгая.
  Future<void> connect(String address);

  /// Отправить готовые команды языка печати.
  Future<void> write(List<int> bytes);

  /// Закрыть соединение.
  Future<void> disconnect();
}
