/// Кодировка Windows-1251 для команд печати (P4-06).
///
/// Зачем своя: в `dart:convert` её нет, а принтер при `CODEPAGE 1251` ждёт именно её — один
/// байт на символ. UTF-8 отдал бы по два байта на букву, и принтер напечатал бы мусор.
///
/// Таблица не нужна целиком: кириллица в CP1251 лежит непрерывным блоком `А`…`я` → 0xC0…0xFF,
/// и из неё выпадают только `Ё` и `ё`. Остальное — ASCII, совпадающий с латиницей один в один.
/// Выписывать двести строк соответствий ради этого значило бы прятать простое правило в таблице.
library;

/// Кодирует строку в CP1251. Символы вне кодировки заменяются на `?` — на этикетке это
/// честнее, чем пропуск: видно, что текст пришёл не тот, а не что он укоротился.
List<int> encodeCp1251(String text) {
  final out = <int>[];
  for (final rune in text.runes) {
    out.add(_byte(rune));
  }
  return out;
}

int _byte(int rune) {
  // ASCII — без изменений.
  if (rune < 0x80) return rune;
  // Основной блок кириллицы: А (U+0410) … я (U+044F) → 0xC0 … 0xFF.
  if (rune >= 0x0410 && rune <= 0x044F) return rune - 0x0410 + 0xC0;
  // Ё и ё стоят в CP1251 отдельно от блока — это и есть всё исключение.
  if (rune == 0x0401) return 0xA8;
  if (rune == 0x0451) return 0xB8;
  // Символы, которые реально встречаются в наименованиях из 1С.
  return switch (rune) {
    0x2116 => 0xB9, // № — номер
    0x00AB => 0xAB, // «
    0x00BB => 0xBB, // »
    0x2013 => 0x96, // – короткое тире
    0x2014 => 0x97, // — длинное тире
    0x2026 => 0x85, // …
    0x00A0 => 0x20, // неразрывный пробел → обычный
    _ => 0x3F, // ?
  };
}
