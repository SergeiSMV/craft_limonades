import 'dart:async';

import 'package:injectable/injectable.dart';
import 'package:talker_flutter/talker_flutter.dart';

import 'scan_code.dart';
import 'scanner_service.dart';

/// Тот, кто может принять код сканера.
///
/// Реализуется миксином [HardwareScanListener], поэтому экраны и диалоги этот интерфейс
/// не пишут руками.
abstract interface class ScanConsumer {
  /// Готов ли принять код прямо сейчас: виджет в дереве, приём не выключен и он верхний
  /// в стопке маршрутов.
  bool get canAcceptScan;

  /// Принять код. `true` - взял, дальше по стопке код не идёт.
  bool acceptScan(ScanCode code);
}

/// Единая точка доставки кодов сканера подписчикам (ADHOC-08).
///
/// Что: держит одну подписку на поток кодов и раздаёт их зарегистрированным получателям.
/// Зачем: до роутера каждый экран подписывался на поток сам и сам решал, его ли это код.
///        Правило «мой ли скан» жило в семи местах, а случай «код не взял никто» не
///        существовал вовсе - скан просто исчезал. Именно так пропадали сканы в диалогах:
///        экран под диалогом перестаёт быть верхним, диалог подписан не был, и код уходил
///        в тишину, не оставляя даже следа в логе.
/// Как: получатели складываются в порядке регистрации, то есть в порядке стопки маршрутов
///      (диалог монтируется после экрана, значит окажется последним). Код предлагается
///      с конца - первому, кто готов его взять. Не взял никто - пишем в лог.
///
/// **Отсечения дублей здесь нет намеренно.** Дубль возникает не в потоке - поток на один скан
/// даёт одно событие. Он возникает у получателя, у которого два входа: поле ввода
/// (клавиатурный режим) и этот поток. Поле роутеру не видно, поэтому сводить источники может
/// только сам получатель, и `ScanDeduper` живёт у него.
@lazySingleton
class ScanRouter {
  ScanRouter(this._scanner, this._talker);

  final ScannerService _scanner;
  final Talker _talker;

  /// Получатели в порядке регистрации: последний зарегистрированный - верхний в стопке.
  final List<ScanConsumer> _consumers = [];

  StreamSubscription<ScanCode>? _subscription;

  /// Сколько получателей сейчас зарегистрировано - для диагностики.
  int get consumerCount => _consumers.length;

  /// Подписаться на коды. Зовётся из [HardwareScanListener], а не из экранов напрямую.
  void register(ScanConsumer consumer) {
    _consumers.add(consumer);
    // Подписка поднимается при первом получателе, а не в конструкторе: без подписчиков
    // держать открытым платформенный поток незачем.
    _subscription ??= _scanner.scans.listen(_dispatch);
  }

  /// Отписаться. Последний ушедший получатель закрывает и подписку на поток.
  void unregister(ScanConsumer consumer) {
    _consumers.remove(consumer);
    if (_consumers.isEmpty) {
      unawaited(_subscription?.cancel());
      _subscription = null;
    }
  }

  /// Раздать код: с конца стопки первому готовому получателю.
  void _dispatch(ScanCode code) {
    // Копия списка: обработчик может открыть диалог или уйти с экрана, то есть изменить
    // состав получателей прямо во время обхода.
    for (final consumer in _consumers.reversed.toList()) {
      if (!consumer.canAcceptScan) continue;
      if (consumer.acceptScan(code)) return;
    }
    // Ветка, которой раньше не было. Скан, который никто не взял, - это либо забытая
    // подписка (так и терялись коды в диалогах), либо осознанное «здесь сканы не нужны».
    // И то, и другое теперь видно в логах устройства, а не только по жалобе кладовщика.
    _talker.warning(
      'Скан никем не обработан: ${code.raw} (${code.kind.name}); '
      'получателей в стопке: ${_consumers.length}',
    );
  }
}
