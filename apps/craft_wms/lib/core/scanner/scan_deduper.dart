/// Отсекает повторную обработку одного и того же скана.
///
/// Зачем: у экрана два входа для кода - поле ввода (клавиатурный режим сканера) и поток
/// broadcast-интентов. Режимы вывода в настройках сканера взаимоисключающие, но настройку правит
/// человек на устройстве, и конфигурация «и то, и другое» приведёт к двойной строке остатка -
/// то есть к неверному количеству на складе. Дешевле отсечь дубль, чем ловить его в пересчёте.
///
/// Как: один и тот же код, пришедший повторно в пределах [window], игнорируется. Разные коды
/// подряд проходят всегда - быстрый скан двух этикеток не страдает.
class ScanDeduper {
  ScanDeduper({this.window = const Duration(milliseconds: 400)});

  /// Окно, в пределах которого повтор того же кода считается дублем доставки.
  final Duration window;

  String? _lastCode;
  DateTime? _lastAt;

  /// Пропускать ли этот код в обработку. [now] - точка времени (в тестах задаётся явно).
  bool allow(String code, {DateTime? now}) {
    final at = now ?? DateTime.now();
    final previousAt = _lastAt;
    if (_lastCode == code &&
        previousAt != null &&
        at.difference(previousAt) < window) {
      return false;
    }
    _lastCode = code;
    _lastAt = at;
    return true;
  }

  /// Сброс истории - после ухода с экрана или явной смены контекста скана.
  void reset() {
    _lastCode = null;
    _lastAt = null;
  }
}
