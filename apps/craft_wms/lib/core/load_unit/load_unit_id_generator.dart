import 'package:injectable/injectable.dart';
import 'package:uuid/uuid.dart';

import 'load_unit_code.dart';

/// Генератор идентификаторов грузовой единицы (P4-04).
///
/// Что: выдаёт новый UUID короба и готовую полезную нагрузку для печати ярлыка.
/// Зачем: ГЕ собирают на приёмке, в том числе без сети, и серверный идентификатор взять неоткуда —
/// ярлык печатается и наклеивается на месте. Сервер к этому готов: `POST /load-units` принимает
/// id с устройства идемпотентно (P4-03).
/// Как: UUID v4 — 122 случайных бита, столкновение недостижимо на складских объёмах, а главное,
/// генерация не требует ни сети, ни согласования с другими терминалами.
///
/// Отдельный класс, а не `const Uuid()` по месту: генерация id и его оболочка для печати — одно
/// решение, и держать его в одной точке дешевле, чем потом искать все места, где собирали ярлык
/// руками. Заодно зависимость внедряется, а не создаётся внутри, — её можно подменить.
@lazySingleton
class LoadUnitIdGenerator {
  const LoadUnitIdGenerator(this._uuid);

  final Uuid _uuid;

  /// Новый идентификатор ГЕ — то, что уезжает на сервер и ложится в `load_units.id`.
  String newId() => _uuid.v4();

  /// Новый ярлык целиком: идентификатор в оболочке формата, готовый к печати в QR (P4-06).
  String newLabelPayload() => encodeLoadUnitPayload(newId());
}
