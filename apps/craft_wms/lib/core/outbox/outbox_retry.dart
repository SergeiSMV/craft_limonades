import '../error/failure.dart';

/// Имеет ли смысл повторять операцию очереди (P2-03/P2-04).
///
/// Повторяем то, что не зависит от содержания запроса: обрыв связи, 5xx, истёкшую сессию.
/// Отказ по существу (4xx — например, 409 «ШК уже за другим товаром») повтором не лечится:
/// сервер ответит тем же, а очередь встанет намертво на неисполнимой операции.
///
/// Правило вынесено из репозитория в общее место: по нему решают двое — тот, кто отправляет
/// операцию сразу при вызове, и движок синхронизации, разгребающий очередь потом. Разойдись
/// они, одна и та же ошибка означала бы разное в зависимости от того, кто её увидел.
bool isRetryable(Failure failure) => switch (failure) {
  NetworkFailure() => true,
  AuthFailure() => true,
  ServerFailure(:final statusCode) => statusCode >= 500,
  UnknownFailure() => true,
};

/// Пауза перед следующей попыткой по числу уже сделанных.
///
/// Нарастает, чтобы терминал не долбил недоступный сервер в цикле: на складе связь пропадает
/// не на секунду, а на минуты (кладовщик ушёл в дальний угол). Потолок — 5 минут: дольше ждать
/// незачем, событие смены сети всё равно разбудит движок раньше.
Duration retryDelay(int attempts) {
  const delays = [
    Duration(seconds: 5),
    Duration(seconds: 15),
    Duration(seconds: 45),
    Duration(minutes: 2),
    Duration(minutes: 5),
  ];
  return delays[attempts.clamp(0, delays.length - 1)];
}
