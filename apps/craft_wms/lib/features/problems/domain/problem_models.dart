/// Проблемы склада на ТСД (P6-07-2): пометка короба или товара браком, изолятором …
///
/// Слой `domain` фичи: ни Flutter, ни сети, ни базы.
library;

/// Причина проблемы — фиксированный список (решение 2026-10-14), как на сервере.
enum ProblemReason {
  /// Бой.
  breakage('breakage'),

  /// Порча.
  spoilage('spoilage'),

  /// Просрок.
  expired('expired'),

  /// Не наша марка ЧЗ.
  foreignMark('foreign_mark'),

  /// Марка ЧЗ выбыла из оборота (CZ-05). Заводит только приёмка по ответу ЧЗ — кладовщику
  /// на выбор не предлагается: без чтения ЧЗ выбытие не установить.
  retired('retired', selectable: false),

  /// Короб или марка не найдены пересчётом (P10-03). Заводит только программа при подсчёте
  /// ячейки — кладовщику на выбор не предлагается.
  notFound('not_found', selectable: false),

  /// Прочее — комментарий обязателен.
  other('other');

  const ProblemReason(this.wire, {this.selectable = true});

  /// Как значение уходит на сервер.
  final String wire;

  /// Причину выбирает кладовщик при пометке; `false` — её ставит только программа.
  final bool selectable;
}
