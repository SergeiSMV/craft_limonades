import '../../../core/error/failure.dart';
import 'contents_entities.dart';
import 'stock_entities.dart';

/// Содержимое ячеек и коробов для экранов (P5-05).
///
/// Что: карточка короба и содержимое ячейки по скану.
/// Зачем абстракция: экраны не знают, откуда данные — с сервера, из снимка на терминале или
/// из своей неотправленной операции. Реализация решает это сама и говорит только «откуда»
/// ([DataFreshness]), чтобы экран честно подписал данные.
/// Как реализовано — `ContentsRepositoryImpl` в `data`: сначала сервер, без связи — снимок,
/// поверх обоих — свои операции очереди в статусах «ожидает» и «отправляется».
abstract interface class ContentsRepository {
  /// Карточка короба по идентификатору из QR ярлыка.
  ///
  /// `Left` — только когда показать нечего вовсе: связи нет и снимка ещё не было.
  Future<Either<Failure, Viewed<LoadUnitView>>> loadUnit(String id);

  /// Адрес ячейки короба [id] без сети (ADHOC-63): снимок терминала со своей очередью поверх.
  /// Зачем: показать, откуда взят пик марки, не дожидаясь сервера на каждый скан. `null` -
  /// короба нет в снимке и в своих операциях.
  Future<String?> cachedLoadUnitCell(String id);

  /// Идентификатор ГЕ короба ЧЗ по коду `00`+SSCC с его этикетки (CZ-06): своего ярлыка у
  /// короба ЧЗ нет. Сервер, без связи — снимок и своя очередь; `null` — короб не принят.
  ///
  /// `Left` — только когда узнать негде: связи нет, снимка не было, своя очередь короб не знает.
  Future<Either<Failure, String?>> loadUnitIdByCzCode(String czCode);

  /// Марки на складе по отсканированному коду (CZ-06): марка — она одна, групповая упаковка —
  /// её марки, где бы они ни лежали. Из снимка терминала со своей очередью поверх: марки
  /// перемещают и без связи, а сервер при проводке проверяет место каждой. Пусто — склад такой
  /// марки не знает (или снимок её ещё не принёс).
  Future<List<StockMark>> marksByCode(String code);

  /// Содержимое ячейки.
  Future<Either<Failure, Viewed<CellView>>> cell(CellRef cell);

  /// Ячейка по отсканированному адресу — из справочника терминала; `null` — такой нет.
  Future<CellRef?> findCell(String address);

  /// Все живые короба склада из снимка, со своей очередью поверх (P5-05-1).
  ///
  /// [refreshFailure] — чем кончилось последнее обновление снимка: `null` — обновился, подпись
  /// «данные на ЧЧ:ММ» не нужна; `NetworkFailure` — нет связи; иное — сервер ответил ошибкой.
  /// Передаётся последний исход, а не «обновляли ли только что»: перечитывание того же снимка
  /// (очистка поиска) не делает его ни старее, ни «без связи» (ADHOC-22).
  Future<Viewed<List<LoadUnitView>>> loadUnits({Failure? refreshFailure});

  /// Короба по короткому коду, уже приведённому [shortCodeQuery]: сервер ответил — все короба
  /// склада, живые и нет; не ответил (нет связи, сбой, старая версия) — снимок и своя очередь.
  Future<Either<Failure, Viewed<List<LoadUnitView>>>> searchLoadUnits(
    String code,
  );

  /// История короба — только со связью.
  Future<Either<Failure, LoadUnitHistory>> history(String id);

  /// Остатки по товарам на всём складе из снимка, со своей очередью поверх (ADHOC-33): только
  /// товары, которых больше нуля. [refreshFailure] — как у [loadUnits].
  Future<Viewed<List<GoodStock>>> goodsStock({Failure? refreshFailure});

  /// Где лежит товар [goodId]: россыпь и короба по ячейкам, из снимка со своей очередью поверх
  /// (ADHOC-33). [refreshFailure] — как у [loadUnits].
  Future<Viewed<List<StockPlace>>> goodPlaces(
    String goodId, {
    Failure? refreshFailure,
  });
}

/// Загрузка снимка содержимого склада в кэш терминала.
///
/// Отдельно от [ContentsRepository]: ей пользуются не экраны, а синхронизация (вместе со
/// справочниками) и очередь (после подтверждения приёмки и размещения).
abstract interface class ContentsSnapshotSync {
  /// Загрузить снимок сейчас.
  Future<Either<Failure, void>> refresh();

  /// Попросить загрузить вскоре: несколько подтверждений подряд дают одну загрузку.
  void requestRefresh();

  /// Снимок в кэше заменён свежим — по любому поводу: вход, очередь, версии данных (ADHOC-60).
  /// Открытые экраны перечитывают себя из кэша, не загружая снимок второй раз.
  Stream<void> get updated;
}
