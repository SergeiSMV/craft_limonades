import 'dart:async';

/// Незавершённое чтение кодов ЧЗ прихода (ADHOC-70) - общее для экранов одного прихода.
///
/// Что: экраны прихода (общий список, страницы коробов) отмечают здесь, что у них есть
/// отсканированные, но ещё не легшие в приход коды ЧЗ; [settle] ждёт, пока они лягут.
/// Зачем: страница прихода сама уходит назад и закрывает ячейку «Ввода остатков», а очередь
/// чтения живёт в экране под ней. Без общего места страница ушла бы раньше, чем марки,
/// отсканированные последними, легли бы в приход, - и они пропали бы.
/// Как: держит незавершённые работы экранов; живёт в кубите прихода, который делят все его
/// экраны.
class CzIntakeHold {
  final _work = <Future<void>>{};

  /// Есть ли незавершённое чтение.
  bool get busy => _work.isNotEmpty;

  /// Отметить работу экрана: она закончится, когда все его коды лягут в приход.
  void track(Future<void> work) {
    _work.add(work);
    unawaited(work.whenComplete(() => _work.remove(work)));
  }

  /// Дождаться всех работ, в том числе отмеченных во время ожидания.
  Future<void> settle() async {
    while (_work.isNotEmpty) {
      await Future.wait(List.of(_work));
    }
  }
}
