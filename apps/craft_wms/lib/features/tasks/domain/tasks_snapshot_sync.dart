/// Обновление снимка текущих заданий на терминале (ADHOC-24).
///
/// Что: попросить подтянуть текущие задания с сервера.
/// Зачем: задание на размещение рождается на сервере при проведении приёмки, а остаток
///        задания меняет проведённое размещение. Пока обе операции идут очередью, терминал
///        узнаёт об этом только по их подтверждению - и без обновления снимка плитка
///        «ЗАДАНИЯ» на главном экране показывала старое число, пока главный экран не откроют
///        заново.
abstract interface class TasksSnapshotSync {
  /// Попросить загрузить вскоре: несколько подтверждений подряд дают одну загрузку.
  void requestRefresh();
}
