import 'package:craft_wms/core/printer/cp1251.dart';
import 'package:flutter_test/flutter_test.dart';

/// Кодировка CP1251 для команд печати (P4-06): принтер при `CODEPAGE 1251` ждёт один байт
/// на символ, и ошибка здесь даёт на этикетке мусор вместо наименования товара.
void main() {
  test('латиница и цифры совпадают с ASCII', () {
    expect(encodeCp1251('AZ09'), [0x41, 0x5A, 0x30, 0x39]);
  });

  test('кириллица ложится в блок 0xC0…0xFF', () {
    // А — первая буква блока, я — последняя: границы и проверяем.
    expect(encodeCp1251('А'), [0xC0]);
    expect(encodeCp1251('я'), [0xFF]);
    expect(encodeCp1251('Кальмар'), [0xCA, 0xE0, 0xEB, 0xFC, 0xEC, 0xE0, 0xF0]);
  });

  test('Ё и ё стоят вне блока — единственное исключение', () {
    expect(encodeCp1251('Ё'), [0xA8]);
    expect(encodeCp1251('ё'), [0xB8]);
  });

  test('знаки из наименований 1С кодируются, а не теряются', () {
    expect(encodeCp1251('№'), [0xB9]);
    expect(encodeCp1251('«»'), [0xAB, 0xBB]);
    expect(encodeCp1251('–—'), [0x96, 0x97]);
    // Неразрывный пробел в выгрузках 1С встречается и ломает разбор — приводим к обычному.
    expect(encodeCp1251(' '), [0x20]);
  });

  test('символ вне кодировки заменяется на «?», а не пропадает', () {
    // Пропуск укоротил бы строку молча, и подмену было бы не видно на этикетке.
    expect(encodeCp1251('日'), [0x3F]);
    expect(encodeCp1251('А日Я').length, 3);
  });

  test('каждый символ — ровно один байт', () {
    // Главное свойство: принтер отсчитывает именно байты, и двухбайтовая кодировка
    // сместила бы весь текст.
    const text = 'Короб №12 «Кальмар»';
    expect(encodeCp1251(text), hasLength(text.length));
  });
}
