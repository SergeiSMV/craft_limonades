#!/usr/bin/env bash
# Craft WMS · обновление сервера «в одну команду» (идемпотентно):
#   1) подтягивает свежий код деплоя (git pull) — скрипты и systemd-юниты;
#   2) переустанавливает юниты, если они изменились;
#   3) тянет свежий образ backend из GHCR; есть новые миграции — снимает дамп базы, применяет
#      миграции, перезапускает изменившееся;
#   4) проверяет /ready и громко ругается в journal, если стек не поднялся.
#
# Безопасно гонять хоть каждые 5 минут: нет изменений — по сути no-op.
#
# Использование:
#   sudo bash deploy/update.sh          # обновить сервер целиком
#   (то же вызывает systemd-таймер craft-wms-update.timer — авто-обновление)
#
# SELF_UPDATE=false в .env.prod отключает шаги 1–2: код деплоя обновляется только вручную.
set -euo pipefail
SCRIPT_NAME=update
# Путь к _lib.sh вычисляется в рантайме — статический анализатор его не проходит,
# и без подсказки ниже SCRIPT_NAME считается неиспользуемым (SC2034).
# Строка с директивой должна содержать только её: текст после пути ломает разбор.
# shellcheck source=deploy/_lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

require_env_file
command -v docker >/dev/null 2>&1 || die "docker не установлен."

# --- 0. Перезапуск из временной копии ---------------------------------------------------
# git pull ниже перепишет ЭТОТ файл. bash дочитывает скрипт с диска по мере выполнения,
# поэтому подмена на ходу приводит к исполнению обрывка новой версии вперемешку со старой.
# Уходим в копию: обновление доедет целиком, а новая версия вступит в силу со следующего
# запуска — сломанный update.sh не сможет оборваться на середине собственного обновления.
if [[ "${CRAFT_SELF_COPY:-}" != "1" && "$(get_env SELF_UPDATE)" != "false" ]]; then
  copy_dir="$(mktemp -d)"
  cp "$DEPLOY_DIR"/*.sh "$copy_dir/"
  trap 'rm -rf "$copy_dir"' EXIT
  log "Работаю из копии $copy_dir (git pull не подменит скрипт на ходу)."
  CRAFT_SELF_COPY=1 CRAFT_REPO_ROOT="$REPO_ROOT" bash "$copy_dir/update.sh" "$@"
  exit $?
fi

# Исход обновления — сигналом мониторингу таймеров (ADHOC-42). Таймер гоняет скрипт каждые 5 минут,
# и сигнал «жив» — это заодно проверка, что сервер на месте: выключенный ноутбук или пропавший
# интернет не шлют ничего, и сервис пишет письмо. Ставится здесь, после перезапуска из копии:
# сигнал отправляет процесс, который делает работу.
job_watch UPDATE

preflight_net

# --- 1. Код деплоя ----------------------------------------------------------------------
if [[ "$(get_env SELF_UPDATE)" != "false" ]]; then
  before_rev="$(git -C "$REPO_ROOT" rev-parse --short HEAD 2>/dev/null || echo '?')"
  log "Обновляю код деплоя (git pull)…"
  # safe.directory: таймер работает от root, а клон принадлежит пользователю сервера —
  # без этого git отказывается работать с «чужим» репозиторием.
  # --ff-only: если в клоне локальные правки и слияние неочевидно, лучше не тронуть
  # боевой сервер, чем молча смержить.
  if git -c safe.directory="$REPO_ROOT" -C "$REPO_ROOT" pull --ff-only --quiet; then
    after_rev="$(git -C "$REPO_ROOT" rev-parse --short HEAD)"
    if [[ "$before_rev" != "$after_rev" ]]; then
      log "Код деплоя обновлён: $before_rev → $after_rev."
      log "Правки в самом update.sh вступят в силу со следующего запуска."
    else
      log "Код деплоя актуален ($after_rev)."
    fi
  else
    journal_err "git pull не прошёл — продолжаю со старым кодом деплоя. Частые причины: remote по HTTPS (в таймере нет терминала, чтобы ввести токен — нужен deploy key по SSH, см. docs/deploy/prod-deploy.md) или локальные правки в $REPO_ROOT."
  fi

  # --- 2. systemd-юниты ---
  # Идемпотентно перезаписываем из репозитория: иначе правки юнитов лежали бы в git
  # и никогда не доезжали до сервера.
  log "Применяю systemd-юниты…"
  install_systemd_units
else
  log "SELF_UPDATE=false — код деплоя и юниты не трогаю."
fi

# --- 3. Образ backend -------------------------------------------------------------------
# Логин в GHCR, если образ приватный (GHCR_USER/GHCR_TOKEN заданы). Публичный логина не требует.
GHCR_USER="$(get_env GHCR_USER)"; GHCR_TOKEN="$(get_env GHCR_TOKEN)"
if [[ -n "$GHCR_USER" && -n "$GHCR_TOKEN" ]]; then
  printf '%s' "$GHCR_TOKEN" | docker login ghcr.io -u "$GHCR_USER" --password-stdin >/dev/null 2>&1 \
    || warn "не удалось залогиниться в GHCR (проверьте GHCR_USER/GHCR_TOKEN)."
fi

# Запоминаем текущий образ backend, чтобы понять, было ли обновление.
before="$(compose images -q backend 2>/dev/null || true)"

log "Проверяю обновления образа…"
# Только backend: postgres прибит по версии и уже лежит локально. Раньше `compose pull`
# без имени сервиса тянул и его из Docker Hub, а тот из России отваливается по TLS —
# под set -e это роняло всё авто-обновление из-за образа, который не менялся.
compose pull --quiet backend || warn "не удалось обновить образ backend — продолжаю с локальным." 

# Миграции применяем всегда (идемпотентно: нет новых — 'no change'). Это дёшево и надёжно.
#
# Порядок важен: миграции идут ДО подъёма нового контейнера. Раньше было наоборот, и упавшая
# миграция оставляла работать новый код против старой схемы: скрипт умирал здесь под set -e,
# а `up -d` к тому моменту уже пересоздал контейнер, и снять его было некому. Снаружи такой
# сервер выглядел здоровым — /ready щупает только доступность БД, про версию схемы не знает.
# Теперь неудачная миграция роняет обновление ДО смены кода: работает прежний контейнер,
# схема прежняя, они друг другу соответствуют.
#
# Образ для migrate берётся уже свежий (pull выше), то есть накатываются миграции новой версии.
# Отдельно поднимать БД не нужно: `compose run` тянет зависимости сервиса, а у backend прописан
# depends_on: db (condition: service_healthy).
# Дамп перед миграциями (ADHOC-37) — только когда есть что применять: таймер гоняет скрипт
# каждые 5 минут, и дамп на каждом запуске забил бы диск. `migrate pending` свежего образа
# отвечает кодом: 0 — есть новые, 3 — схема актуальна, прочее — не удалось узнать. В последнем
# случае дамп снимаем: лишний дамп дешевле миграции без точки восстановления. Так и при
# первой выкатке, если update.sh приехал раньше образа, где `pending` уже есть.
pending_rc=0
compose run --rm --entrypoint /usr/local/bin/migrate backend pending || pending_rc=$?
case "$pending_rc" in
  3) log "Новых миграций нет — дамп не нужен." ;;
  0) premigrate_dump ;;
  *) warn "не удалось узнать, есть ли новые миграции (код $pending_rc) — дамп снимаю на всякий случай."
     premigrate_dump ;;
esac

log "Миграции…"
compose run --rm --entrypoint /usr/local/bin/migrate backend up

log "Применяю (up -d — пересоздаст контейнер только при новом образе)…"
compose up -d

# Считаем ПОСЛЕ up -d: `compose images` отдаёт образ созданного контейнера, а не скачанный
# pull'ом, — до пересоздания здесь был бы прежний id, и обновление всегда выглядело бы «нет новых».
after="$(compose images -q backend 2>/dev/null || true)"

if [[ "$before" != "$after" ]]; then
  log "Обновление применено: образ backend изменился."
else
  log "Новых обновлений образа нет."
fi

# --- 3b. Веб-портал -----------------------------------------------------------------------
# Бандл приезжает отдельным образом. Неудача здесь не должна ронять обновление backend:
# портал важен, но менее критичен, чем работающее API на ТСД.
portal_deploy || journal_err "портал обновить не удалось — работает прежний бандл." 

# --- 4. Проверка готовности -------------------------------------------------------------
# Без неё ночное падение обнаружилось бы утром по жалобе кладовщика.
health_check || die "обновление применено, но стек не отвечает — смотрите: docker compose logs backend"

# --- 5. Путь снаружи: хостовый nginx и сертификат (ADHOC-42) ---
# health_check щупает бэкенд на loopback, мимо nginx. Здесь тот же /ready — через nginx и TLS
# по имени домена (адрес подменён на сам сервер: из LAN внешнее имя не открывается). Упал nginx
# или истёк сертификат — скрипт падает, и сигнал «упал» уносит причину.
domain="$(get_env DEPLOY_DOMAIN)"
if [[ -n "$domain" ]]; then
  curl -fsS -m 10 -o /dev/null --resolve "$domain:443:127.0.0.1" "https://$domain/ready" \
    || die "https://$domain/ready через nginx не отвечает — nginx или сертификат (не истёк ли?)."
fi
log "Обновление завершено."
